"""Builds fees.json from every source.

    python -m feezer_tables.build            # scrape and write fees.json
    python -m feezer_tables.build --check    # only validate fees.json

A source that fails keeps its previously published grids, and the command
exits with status 1 so the scheduled workflow is reported as failed.

updatedAt is the date the grids last changed; checkedAt the date of the last
run.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
import traceback
from pathlib import Path

from . import manual, mvola, orange
from .http import Fetcher
from .model import Grid, validate

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "fees.json"
SCHEMA = 2

# The published grids are open data: reuse them with this attribution and under
# the same license (the scraper code itself is GPL-3.0, see LICENSE).
LICENSE = "CC-BY-SA-4.0"
ATTRIBUTION = "Feezer fee tables, https://github.com/elsycharles/feezer-fee-tables"

# (label, collector, selector of the previously published grids to keep when
# the collector fails).
SOURCES = (
    (mvola.NAME, mvola.collect, lambda g: g.name == mvola.NAME),
    (orange.NAME, orange.collect, lambda g: g.name == orange.NAME),
    ("manual sources", manual.collect, lambda g: g.source_type == "manual"),
)


def load(path: Path = OUTPUT) -> dict:
    if not path.exists():
        return {"schema": SCHEMA, "updatedAt": None, "providers": []}
    return json.loads(path.read_text(encoding="utf-8"))


def previous_grids(document: dict) -> list[Grid]:
    if document.get("schema") != SCHEMA:
        return []
    return [Grid.from_json(p) for p in document.get("providers", [])]


def render(grids: list[Grid], updated_at: str | None, checked_at: str | None = None) -> str:
    document = {
        "schema": SCHEMA,
        "updatedAt": updated_at,
        "checkedAt": checked_at,
        "note": (
            "Fees charged to the sender, in Ariary. min and max are the "
            "amount sent, both included. Generated by feezer_tables; do not "
            "edit by hand except sources/*.json."
        ),
        "license": LICENSE,
        "attribution": ATTRIBUTION,
        "providers": [g.to_json() for g in grids],
    }
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def collect_all(fetcher: Fetcher, previous: list[Grid]) -> tuple[list[Grid], list[str]]:
    grids: list[Grid] = []
    failures: list[str] = []
    for label, collector, belongs in SOURCES:
        try:
            collected = collector(fetcher)
            if not collected:
                raise RuntimeError("no grid")
            for grid in collected:
                validate(grid)
            grids.extend(collected)
        except Exception as error:  # noqa: BLE001 - report every failure
            failures.append(f"{label}: {error}")
            traceback.print_exc()
            kept = [g for g in previous if belongs(g)]
            grids.extend(kept)
            print(f"Keeping {len(kept)} previous grid(s) for {label}", file=sys.stderr)
    # A manual grid never overrides a scraped one for the same operation.
    scraped = {g.key() for g in grids if g.source_type == "official"}
    grids = [g for g in grids if g.source_type == "official" or g.key() not in scraped]
    unique: dict[tuple[str, str], Grid] = {}
    for grid in grids:
        unique.setdefault(grid.key(), grid)
    return sorted(unique.values(), key=lambda g: (g.name.lower(), g.operation)), failures


def build(fetcher: Fetcher | None = None, output: Path = OUTPUT) -> int:
    document = load(output)
    previous = previous_grids(document)
    grids, failures = collect_all(fetcher or Fetcher(), previous)
    if not grids:
        print("No grid collected, fees.json left untouched", file=sys.stderr)
        return 1

    ordered_previous = sorted(previous, key=lambda g: (g.name.lower(), g.operation))
    unchanged = render(grids, document.get("updatedAt")) == render(
        ordered_previous, document.get("updatedAt")
    )
    today = dt.date.today().isoformat()
    updated_at = document.get("updatedAt") if unchanged else today
    # checkedAt changes every run: the app shows it, and the daily commit keeps
    # the scheduled workflow alive (GitHub disables it after 60 idle days).
    output.write_text(render(grids, updated_at, today), encoding="utf-8")
    print(f"{len(grids)} grids, {'unchanged' if unchanged else 'updated'}")
    for failure in failures:
        print(f"FAILED {failure}", file=sys.stderr)
    return 1 if failures else 0


def check(path: Path = OUTPUT) -> int:
    document = load(path)
    if document.get("schema") != SCHEMA:
        print(f"Unexpected schema {document.get('schema')}", file=sys.stderr)
        return 1
    seen = set()
    for grid in previous_grids(document):
        validate(grid)
        if grid.key() in seen:
            print(f"Duplicate grid {grid.key()}", file=sys.stderr)
            return 1
        seen.add(grid.key())
    print(f"fees.json OK ({len(seen)} grids)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate only")
    args = parser.parse_args(argv)
    return check() if args.check else build()


if __name__ == "__main__":
    sys.exit(main())
